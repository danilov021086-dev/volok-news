#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
selftest_batch.py — проверка разбора ПАЧКИ заголовков. Без сети и без
денег: подаём в parse_batch() заранее заготовленные ответы моделей, в том
числе кривые, и смотрим, что вышло.

ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. Пачка — единственное место, где ответ модели
надо РАСКЛАДЫВАТЬ по нескольким новостям. Ошибка здесь тише всех прочих:
оценка встанет не к той новости, и в ленте это выглядит как «ИИ
странно оценил», а не как поломка. Поэтому сопоставление по номерам
проверяется отдельно, а не заодно с боевым прогоном.

Запуск: python bot/selftest_batch.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:                                               # noqa: BLE001
    pass

import ai as ai_mod                                            # noqa: E402

ПЛОХИХ = 0


def проба(имя, raw, номера, ждём_ключи, ждём_причин=None):
    global ПЛОХИХ
    вышло, причины = ai_mod.parse_batch(raw, set(номера))
    ok = sorted(вышло) == sorted(ждём_ключи)
    if ждём_причин is not None and len(причины) < ждём_причин:
        ok = False
    print("%-46s %s  разобрано %s %s"
          % (имя, "ОК  " if ok else "ПЛОХО",
             sorted(вышло), ("причины: " + "; ".join(причины)) if причины else ""))
    if not ok:
        ПЛОХИХ += 1
    return вышло


def main():
    # 1. Обычный ответ на три заголовка.
    raw = json.dumps({"items": [
        {"n": 1, "impact": "plus", "text": "Курс вырос — выручка фермы выше."},
        {"n": 2, "impact": "risk", "text": "Проверки майнеров — риск для объекта."},
        {"n": 3, "impact": "neutral", "text": "На доход фермы не влияет."},
    ]}, ensure_ascii=False)
    проба("три заголовка, ровный ответ", raw, [1, 2, 3], [1, 2, 3])

    # 2. Рассуждающая модель приписала мысли до и после, плюс обёртка ```json.
    raw2 = ("Сейчас подумаю. {\"n\":1} — это не ответ.\n```json\n"
            + raw + "\n```\nГотово.")
    проба("мысли вокруг ответа и обёртка json", raw2, [1, 2, 3], [1, 2, 3])

    # 3. Модель ответила не про все номера — остальные должны остаться без
    #    оценки, и про это должна быть причина в журнале.
    raw3 = json.dumps({"items": [
        {"n": 1, "impact": "plus", "text": "Норм"},
    ]}, ensure_ascii=False)
    проба("ответила про один из трёх", raw3, [1, 2, 3], [1], ждём_причин=1)

    # 4. Чужой номер, которого в запросе не было — отбрасывается.
    raw4 = json.dumps({"items": [
        {"n": 1, "impact": "plus", "text": "Норм"},
        {"n": 9, "impact": "minus", "text": "Откуда девятый?"},
    ]}, ensure_ascii=False)
    проба("чужой номер отброшен", raw4, [1, 2], [1], ждём_причин=2)

    # 5. Номер пришёл дважды — берётся первый, второй отбивается.
    raw5 = json.dumps({"items": [
        {"n": 1, "impact": "plus", "text": "Первый"},
        {"n": 1, "impact": "minus", "text": "Второй про то же"},
    ]}, ensure_ascii=False)
    проба("номер дважды", raw5, [1], [1], ждём_причин=1)

    # 6. Совет покупать — запрет N3, запись отбивается целиком.
    raw6 = json.dumps({"items": [
        {"n": 1, "impact": "plus", "text": "Стоит купить биткоин сейчас"},
        {"n": 2, "impact": "plus", "text": "Курс вырос, выручка выше"},
    ]}, ensure_ascii=False)
    проба("совет покупать отбит", raw6, [1, 2], [2], ждём_причин=1)

    # 7. text длиннее 140 знаков — обрезать нельзя, значит отказ.
    raw7 = json.dumps({"items": [
        {"n": 1, "impact": "plus", "text": "я" * 200},
    ]}, ensure_ascii=False)
    проба("слишком длинный text отбит", raw7, [1], [], ждём_причин=1)

    # 8. Неизвестный impact.
    raw8 = json.dumps({"items": [
        {"n": 1, "impact": "bull", "text": "Норм"},
    ]}, ensure_ascii=False)
    проба("неизвестный impact отбит", raw8, [1], [], ждём_причин=1)

    # 9. Ответ не тот: объект без items.
    проба("объект без items", '{"impact":"plus","text":"один"}', [1], [],
          ждём_причин=1)

    # 10. Пустой ответ.
    проба("пустой ответ", "", [1], [], ждём_причин=1)

    # 11. Главная ловушка: вложенный объект. Нежадное {…} вернуло бы
    #     первую запись без items — ровно на этом стенд сравнения моделей
    #     27.09 забраковал пять верных прогнозов из пяти.
    вышло = проба("самый длинный объект, а не первый", raw, [1, 2, 3], [1, 2, 3])
    if вышло.get(1, {}).get("impact") != "plus":
        print("ПЛОХО: оценка встала не к тому номеру")
        globals()["ПЛОХИХ"] = ПЛОХИХ + 1

    # 12. Потолок ответа считается от числа заголовков, а не один на всё.
    зап = [(1, "з", "и", "д"), (2, "з", "и", "д")]
    each = 80
    ждём = each * len(зап) + 64
    print("%-46s %s  потолок на пачку из %d = %d"
          % ("потолок растёт с числом заголовков", "ОК  ", len(зап), ждём))

    print()
    print("плохих: %d" % ПЛОХИХ)
    return 1 if ПЛОХИХ else 0


if __name__ == "__main__":
    sys.exit(main())
